// `divergence-report` (decision 1): the report with IDs, labels, pages and counts goes to the local notes
// folder (decision 59); both wordings side by side go only to the gitignored .cache/ (decision 23).

using System.Text;
using IngestionPipeline.Corpus;
using IngestionPipeline.Pdf;
using UglyToad.PdfPig;
using WoundRag.Shared.Tokenization;

namespace IngestionPipeline.Commands;

public sealed class DivergenceReportCommand(RepoPaths paths) : ICommand
{
    public string Name => "divergence-report";

    public string Usage => "divergence-report";

    public Task<int> RunAsync(string[] args) => Task.FromResult(Run());

    private int Run()
    {
        var aliases = AliasFile.Read(Path.Combine(paths.Patterns, "label_aliases.yaml"))!;
        var sections = SectionsFile.Read(Path.Combine(paths.Patterns, "sections.yaml"))!;
        var annotation = AnnotationFile.Read(Path.Combine(paths.Patterns, "annotation.yaml"))!;
        using var pdf = PdfDocument.Open(paths.SourcePdf);
        var running = TableChunks.RunningText(pdf, GuidelineDocument.Load(pdf), paths.Corpus);
        var recs = RecommendationChunks.Build(running, aliases, sections, WordPieceCounter.Load(paths.Vocabulary));
        var rows = Divergence.Rows(recs, new Annotator(annotation));

        var md = new StringBuilder();
        md.AppendLine("# List / body divergence report");
        md.AppendLine();
        md.AppendLine("**Generated by** `ingestion-pipeline -- divergence-report` · **Implements** decision 1 of");
        md.AppendLine("`demo-reference/decisions/2026-09-28-m4-corpus-decisions.md`. Do not edit by hand; regenerate.");
        md.AppendLine();
        md.AppendLine("The body wording is canonical (decision 1); the list wording is stored as `variant_text`. This");
        md.AppendLine("report lists every recommendation whose two wordings differ, compared as lowercase words.");
        md.AppendLine("**No guideline text is in this file** (decision 23): the wordings side by side, with the");
        md.AppendLine("differing words marked, are in `research/IT23294202/guideline-corpus/.cache/divergence_review.md` (gitignored).");
        md.AppendLine();
        md.AppendLine($"- Recommendations: {recs.Count}; wordings differ: **{rows.Count}**.");
        md.AppendLine($"- Word-identical up to the GRADE / best-practice marker (the difference is in or after the marker): {rows.Count(r => r.MarkerOnly)}.");
        md.AppendLine($"- A differing word lies inside a population clause: {rows.Count(r => r.TouchesClause)}.");
        md.AppendLine($"- A differing word contains a digit: {rows.Count(r => r.TouchesNumber)}.");
        md.AppendLine($"- **For clinician review** (clause or number): **{rows.Count(r => r.ClinicianReview)}**.");
        md.AppendLine();
        md.AppendLine($"Population clauses come from `research/IT23294202/guideline-corpus/patterns/annotation.yaml` (status: **{annotation.Status}**, decision 21).");
        md.AppendLine("This report stays local (decision 59); regenerate it whenever those patterns change.");
        md.AppendLine();
        md.AppendLine("| Chunk | List label | Body label | pdf_index | Words only in body | Words only in list | Same up to marker | Clause | Number | Clinician review |");
        md.AppendLine("|---|---|---|---:|---:|---:|---|---|---|---|");
        foreach (var r in rows)
            md.AppendLine($"| {r.ChunkId} | {r.ListLabel} | {r.BodyLabel} | {r.PdfIndex} | {r.OnlyInBody.Count} | {r.OnlyInList.Count} | " +
                          $"{Yes(r.MarkerOnly)} | {Yes(r.TouchesClause)} | {Yes(r.TouchesNumber)} | {(r.ClinicianReview ? "**yes**" : "")} |");
        Directory.CreateDirectory(paths.Notes);
        var reportPath = Path.Combine(paths.Notes, "divergence-report.md");
        File.WriteAllText(reportPath, md.ToString(), new UTF8Encoding(false));

        var review = new StringBuilder("# Divergence review (generated; gitignored: guideline text)\n\n" +
            "⟦…⟧ marks a word with no partner in the other wording.\n\n");
        var byId = recs.ToDictionary(r => r.ChunkId);
        foreach (var r in rows.OrderByDescending(r => r.ClinicianReview))
        {
            var c = byId[r.ChunkId];
            review.AppendLine($"## {r.ChunkId} — list {r.ListLabel}, body {r.BodyLabel}, pdf_index {r.PdfIndex}" +
                              (r.ClinicianReview ? " — CLINICIAN REVIEW" : ""));
            review.AppendLine();
            review.AppendLine("Body: " + Mark(c.Text[(c.ContextHeader.Length + 1)..], r.OnlyInBody));
            review.AppendLine();
            review.AppendLine("List: " + Mark(c.VariantText, r.OnlyInList));
            review.AppendLine();
        }
        File.WriteAllText(Path.Combine(paths.Cache, "divergence_review.md"), review.ToString(), new UTF8Encoding(false));

        Console.WriteLine($"diverging {rows.Count} of {recs.Count}; marker only {rows.Count(r => r.MarkerOnly)}; " +
                          $"clause {rows.Count(r => r.TouchesClause)}; number {rows.Count(r => r.TouchesNumber)}; clinician review {rows.Count(r => r.ClinicianReview)}");
        Console.WriteLine($"wrote {Path.GetRelativePath(paths.Root, reportPath)} (no text, local) and " +
                          $"{Path.GetRelativePath(paths.Root, paths.Cache)}/divergence_review.md (gitignored)");
        return 0;
    }

    private static string Yes(bool b) => b ? "yes" : "";

    private static string Mark(string s, List<WordAt> words)
    {
        var sb = new StringBuilder();
        var at = 0;
        foreach (var w in words.OrderBy(w => w.Start))
        {
            sb.Append(s, at, w.Start - at).Append('⟦').Append(s, w.Start, w.End - w.Start).Append('⟧');
            at = w.End;
        }
        return sb.Append(s, at, s.Length - at).ToString();
    }
}
